    /// <summary>已知字形与它们的路径数据：图标动效按字形认语义时拿来做指纹比对。</summary>
    internal static IReadOnlyDictionary<string, string> GlyphPaths => PathData;

    /// <summary>
    /// 清空字形几何缓存，返回清掉的条目数（18 篇 §3 的 L0 档）。
    /// </summary>
    /// <remarks>
    /// 这份缓存只是「同一字形不重复解析路径」的加速层：清空后下一次绑定会重新
    /// <see cref="StreamGeometry.Parse"/>，导航栏的显示不变。已经绑到控件上的几何体
    /// 由控件自己持有引用，所以清缓存不会让现有图标消失。
    /// </remarks>
    public static int ClearCache()
    {
        lock (Cache)
        {
            var released = Cache.Count;
            Cache.Clear();
            return released;
        }
    }

    public object? Convert(object? value, Type targetType, object? parameter, CultureInfo culture)
    {
        if (value is not string glyph || string.IsNullOrWhiteSpace(glyph))
        {
            return null;
        }

        lock (Cache)
        {
            if (Cache.TryGetValue(glyph, out var cached))
            {
                return cached;
            }

            if (PathData.TryGetValue(glyph, out var data))
            {
                var geom = StreamGeometry.Parse(data);
                Cache[glyph] = geom;
                return geom;
            }

            // 插件自述的图标名不受宿主控制：认不出来时退回通用插件图标，
            // 而不是返回 null 让导航栏留一个空位（用户只会觉得"这页没图标"，不会想到是名字拼错）。
            if (PathData.TryGetValue("Puzzle", out var fallback))
            {
                var geom = StreamGeometry.Parse(fallback);
                Cache[glyph] = geom;
                return geom;
            }
        }

        return null;
    }

    public object? ConvertBack(object? value, Type targetType, object? parameter, CultureInfo culture) => throw new NotSupportedException();
