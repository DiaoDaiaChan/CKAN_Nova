    public static Geometry? Resolve(string? name)
    {
        if (string.IsNullOrWhiteSpace(name))
        {
            return null;
        }

        var key = name.Trim();
        if (Cache.TryGetValue(key, out var cached))
        {
            return cached;
        }

        if (!PathData.TryGetValue(key, out var data))
        {
            return null;
        }

        var geometry = Geometry.Parse(data);
        Cache[key] = geometry;
        return geometry;
    }
